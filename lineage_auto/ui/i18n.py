LANGUAGES = ("ko", "en", "vi")


class Translator:
    """Holds the active language and hands out strings."""

    def __init__(self, lang="ko"):
        self.lang = lang if lang in LANGUAGES else "ko"

    def toggle(self):
        # The button shows the next language: ko -> en -> vi -> ko.
        self.lang = LANGUAGES[(LANGUAGES.index(self.lang) + 1) % len(LANGUAGES)]
        return self.lang

    def t(self, translation_key, **kwargs):
        text = I18N.get(self.lang, I18N["en"]).get(translation_key, translation_key)
        return text.format(**kwargs) if kwargs else text

    def class_name(self, character):
        return character.display_name(self.lang)

    def map_name(self, hunt):
        return hunt.display_name(self.lang)
